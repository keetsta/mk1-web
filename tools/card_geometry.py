"""The front of the MK-1 card for the preview, straight from the board: mk1-card/card.kicad_pcb ->
src/mk1/preview/geometry.ts. Millimetres from the board's top-left corner, y down.

python3 tools/card_geometry.py ../mk1-card src/mk1/preview/geometry.ts
"""
import math, os, subprocess, sys

card, out = sys.argv[1], sys.argv[2]
sys.path.insert(0, os.path.join(card, 'tools'))
import sexp  # mk1-card's own s-expression reader

pcb = sexp.load(os.path.join(card, 'card.kicad_pcb'))


def kids(node, name):
    return [k for k in node[1:] if isinstance(k, list) and k and k[0] == name]


def kid(node, name):
    ks = kids(node, name)
    return ks[0] if ks else None


def xy(node):
    return float(node[1]), float(node[2])


def layer(node):
    lay = kid(node, 'layer')
    return str(lay[1]) if lay else None


# board outline: four lines and four corner arcs on Edge.Cuts
pts, radius = [], 0.0
for n in kids(pcb, 'gr_line') + kids(pcb, 'gr_arc'):
    if layer(n) != 'Edge.Cuts':
        continue
    ends = [xy(kid(n, 'start')), xy(kid(n, 'end'))]
    pts += ends
    if n[0] == 'gr_arc':
        (ax, ay), (mx, my), (bx, by) = ends[0], xy(kid(n, 'mid')), ends[1]
        d = 2 * (ax * (my - by) + mx * (by - ay) + bx * (ay - my))
        ux = ((ax**2 + ay**2) * (my - by) + (mx**2 + my**2) * (by - ay) + (bx**2 + by**2) * (ay - my)) / d
        uy = ((ax**2 + ay**2) * (bx - mx) + (mx**2 + my**2) * (ax - bx) + (bx**2 + by**2) * (mx - ax)) / d
        radius = math.dist((ux, uy), (ax, ay))
ox, oy = min(p[0] for p in pts), min(p[1] for p in pts)
W, H = max(p[0] for p in pts) - ox, max(p[1] for p in pts) - oy


def fab_box(fp):
    """the part's body: the bounding box of its F.Fab drawing, in the footprint's own frame"""
    xs, ys = [], []
    for n in fp[1:]:
        if not (isinstance(n, list) and n and n[0] in ('fp_line', 'fp_rect', 'fp_poly', 'fp_circle')):
            continue
        if layer(n) != 'F.Fab':
            continue
        for key in ('start', 'end', 'center'):
            k = kid(n, key)
            if k:
                xs.append(float(k[1])); ys.append(float(k[2]))
        p = kid(n, 'pts')
        if p:
            for q in kids(p, 'xy'):
                xs.append(float(q[1])); ys.append(float(q[2]))
    if not xs:
        return None
    return min(xs), min(ys), max(xs), max(ys)


parts = {}
for fp in kids(pcb, 'footprint'):
    if layer(fp) != 'F.Cu':
        continue
    ref = next(str(p[2]) for p in kids(fp, 'property') if str(p[1]) == 'Reference')
    at = kid(fp, 'at')
    x, y = float(at[1]) - ox, float(at[2]) - oy
    rot = float(at[3]) if len(at) > 3 else 0.0
    parts[ref] = (x, y, rot, fab_box(fp))

leds = []
for i in range(144):
    x, y, rot, _ = parts[f'D{i + 1}']
    leds.append(f'[{x:.3f}, {y:.3f}, {rot:g}]')


def body(ref):
    """centre, size and rotation of a part's body, so the preview can draw it as a rotated box"""
    x, y, rot, box = parts[ref]
    x0, y0, x1, y1 = box
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    a = math.radians(-rot)                    # KiCad turns counter-clockwise with y down
    return (f'{{ x: {x + cx * math.cos(a) - cy * math.sin(a):.3f}, y: {y + cx * math.sin(a) + cy * math.cos(a):.3f}, '
            f'w: {x1 - x0:.3f}, h: {y1 - y0:.3f}, rot: {(-rot) or 0.0:g} }}')


silk = []
for n in kids(pcb, 'gr_poly'):
    if layer(n) != 'F.SilkS':
        continue
    p = [(float(q[1]) - ox, float(q[2]) - oy) for q in kids(kid(n, 'pts'), 'xy')]
    silk.append('M' + 'L'.join(f'{a:.2f} {b:.2f}' for a, b in p) + 'Z')

rev = subprocess.run(['git', '-C', card, 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip()
with open(out, 'w') as fh:
    fh.write(f'''// The front of the card, generated by tools/card_geometry.py from mk1-card@{rev} (card.kicad_pcb).
// Millimetres from the board's top-left corner, y down. Do not edit: run `npm run geometry`.

export const BOARD = {{ w: {W:.3f}, h: {H:.3f}, r: {radius:.3f} }};

/** LED centres in matrix order (index = row * 16 + column) and their rotation, degrees clockwise */
export const LEDS: readonly (readonly [number, number, number])[] = [
  {', '.join(leds)},
];

export type Body = {{ x: number; y: number; w: number; h: number; rot: number }};
export const BUTTON: Body = {body('SW1')};
export const SENSOR: Body = {body('U6')};
export const USB: Body = {body('J1')};

/** the front silkscreen: the name cut by the board's edge, and keetsta.me */
export const SILK = "{''.join(silk)}";
''')
print(f'{W:.2f} x {H:.2f} mm, r {radius:.2f}; {len(leds)} LEDs; {len(silk)} silk polygons; '
      f'{os.path.getsize(out) // 1024} KB')
